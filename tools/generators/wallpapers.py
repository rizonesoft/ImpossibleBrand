"""The four designed wallpaper pairs (aurora, glass, fluid, contours) for Impossible OS, each as a light and a dark SVG at 3840 x 2160.

Deterministic: every random choice comes from a seeded generator, so a second run writes identical files.
python3 wallpapers_new.py <out dir> [name ...]"""
import math
import random
import sys
from pathlib import Path

W, H = 3840, 2160
OUT = Path(sys.argv[1])
OUT.mkdir(parents=True, exist_ok=True)
ONLY = set(sys.argv[2:])

# Shared palettes: the brand blues and violets, deep for dark, airy for light.
DARK = {"top": "#050A1F", "bottom": "#0B1A4A", "blue": "#2E6BFF", "cyan": "#3FB6FF", "violet": "#7A5CFF", "ink": "#020515", "line": "#5FA8FF"}
LIGHT = {"top": "#F7F9FD", "bottom": "#DCE7F8", "blue": "#5B8CFF", "cyan": "#7CC4FF", "violet": "#A893FF", "ink": "#C9D8F0", "line": "#4C7FE0"}


def doc(title, body, defs=""):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}">\n'
            f'  <!-- Impossible OS wallpaper: "{title}". Original artwork, GPL-3.0-only. Generated by tools/generators/wallpapers.py; edit the generator, not this file. -->\n'
            f'  <defs>{defs}</defs>\n{body}\n</svg>\n')


def sky(p, gid="sky", angle_y=1):
    return (f'<linearGradient id="{gid}" x1="0" y1="0" x2="0" y2="{angle_y}"><stop offset="0" stop-color="{p["top"]}"/>'
            f'<stop offset="1" stop-color="{p["bottom"]}"/></linearGradient>')


def blur(fid, sd):
    # Room for the whole blur (three deviations) around small shapes, or the glow is cut off square.
    return f'<filter id="{fid}" x="-150%" y="-150%" width="400%" height="400%"><feGaussianBlur stdDeviation="{sd}"/></filter>'


def smooth(points, closed=False):
    """A Catmull-Rom curve through the points, as cubic Bezier path data."""
    n = len(points)
    d = f"M{points[0][0]:.1f} {points[0][1]:.1f}"
    rng = range(n) if closed else range(n - 1)
    for i in rng:
        p0 = points[(i - 1) % n] if closed or i > 0 else points[0]
        p1, p2 = points[i], points[(i + 1) % n]
        p3 = points[(i + 2) % n] if closed or i + 2 < n else points[-1]
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        d += f"C{c1[0]:.1f} {c1[1]:.1f} {c2[0]:.1f} {c2[1]:.1f} {p2[0]:.1f} {p2[1]:.1f}"
    return d + ("Z" if closed else "")


def aurora(p, dark):
    """Three curtains of light, each a run of thin vertical rays along a flowing baseline, bright at the foot."""
    r = random.Random(11)
    defs = sky(p) + blur("rays", 9) + blur("glow", 80) + blur("haze", 140)
    body = [f'<rect width="{W}" height="{H}" fill="url(#sky)"/>']
    if dark:
        body.append("".join(f'<circle cx="{r.uniform(0, W):.0f}" cy="{r.uniform(0, H * .6):.0f}" r="{r.choice((1.6, 2.2, 3)):.1f}" fill="#FFFFFF" fill-opacity="{r.uniform(.35, .9):.2f}"/>' for _ in range(220)))
    ribbons = [(p["cyan"], 1150, 170, 1500, 0.4), (p["blue"], 1000, 130, 1100, 2.1), (p["violet"], 880, 110, 900, 4.0)]
    for i, (c, base, amp, wave, phase) in enumerate(ribbons):
        defs += (f'<linearGradient id="ray{i}" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="{c}" stop-opacity="0"/>'
                 f'<stop offset=".7" stop-color="{c}" stop-opacity="{.55 if dark else .4}"/><stop offset=".96" stop-color="{mix(c, "#FFFFFF", .35)}" stop-opacity="{.95 if dark else .75}"/>'
                 f'<stop offset="1" stop-color="{c}" stop-opacity="0"/></linearGradient>')
        rays = []
        for x in range(-100, W + 100, 11):
            foot = base + amp * math.sin(x / wave + phase) + .4 * amp * math.sin(x / (wave * .37) + 2 * phase)
            length = 520 + 260 * math.sin(x / (wave * .6) + phase * 1.7) + r.uniform(-60, 60)
            rays.append(f'<rect x="{x}" y="{foot - length:.0f}" width="14" height="{length:.0f}" fill="url(#ray{i})"/>')
        group = "".join(rays)
        body.append(f'<g filter="url(#glow)" opacity=".7">{group}</g><g filter="url(#rays)">{group}</g>')
    body.append(f'<ellipse cx="{W / 2}" cy="{H + 300}" rx="{W * .7}" ry="700" fill="{p["ink"]}" fill-opacity="{.85 if dark else .5}" filter="url(#haze)"/>')
    return doc("aurora", "\n".join(body), defs)


def glass(p, dark):
    r = random.Random(37)
    defs = sky(p) + blur("soft", 50) + blur("wide", 160)
    body = [f'<rect width="{W}" height="{H}" fill="url(#sky)"/>',
            f'<circle cx="{W * .62}" cy="{H * .5}" r="760" fill="{p["blue"]}" fill-opacity="{.55 if dark else .35}" filter="url(#wide)"/>',
            f'<circle cx="{W * .42}" cy="{H * .62}" r="520" fill="{p["violet"]}" fill-opacity="{.45 if dark else .3}" filter="url(#wide)"/>']
    panes = [(1500, 520, 1300, 900, -14), (2100, 820, 1200, 820, 9), (1250, 1080, 980, 700, 21), (2500, 380, 760, 560, -27)]
    for i, (x, y, w, h, a) in enumerate(panes):
        c = (p["cyan"], p["blue"], p["violet"], p["cyan"])[i]
        defs += (f'<linearGradient id="g{i}" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#FFFFFF" stop-opacity="{.22 if dark else .65}"/>'
                 f'<stop offset="1" stop-color="{c}" stop-opacity="{.18 if dark else .35}"/></linearGradient>')
        tr = f'rotate({a + r.uniform(-2, 2):.1f} {x + w / 2} {y + h / 2})'
        body.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="72" fill="{p["ink"]}" fill-opacity="{.35 if dark else .12}" filter="url(#soft)" transform="translate(30 50) {tr}"/>')
        body.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="72" fill="url(#g{i})" stroke="#FFFFFF" stroke-opacity="{.35 if dark else .8}" stroke-width="4" transform="{tr}"/>')
    return doc("glass", "\n".join(body), defs)



def fluid(p, dark):
    r = random.Random(53)
    # The blur reads transparency from beyond the canvas, so the ground under the blobs carries their own colours:
    # the softened edge then fades into the same hues instead of into a pale or dark frame.
    defs = blur("melt", 260) + (f'<linearGradient id="ground" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="{mix(p["violet"], p["bottom"], .35)}"/>'
                                f'<stop offset=".5" stop-color="{mix(p["blue"], p["bottom"], .3)}"/><stop offset="1" stop-color="{mix(p["cyan"], p["bottom"], .35)}"/></linearGradient>')
    body = [f'<rect width="{W}" height="{H}" fill="url(#ground)"/>']
    # Blobs reach past every edge, so the colour runs off the screen instead of leaving a frame.
    blobs = [(.2, .3, 900, p["violet"]), (.55, .25, 1000, p["blue"]), (.85, .55, 950, p["cyan"]), (.35, .8, 1000, p["blue"]),
             (.7, .9, 800, p["violet"]), (.05, .85, 700, p["cyan"]), (-.05, -.1, 900, p["blue"]), (1.05, -.1, 900, p["violet"]),
             (1.08, 1.1, 900, p["blue"]), (-.08, 1.1, 800, p["violet"]), (.5, -.15, 800, p["cyan"]), (.45, 1.15, 800, p["cyan"])]
    g = ['<g filter="url(#melt)">']
    for x, y, rad, c in blobs:
        pts_ = [(W * x + rad * (1 + .25 * r.uniform(-1, 1)) * math.cos(k * math.pi / 4), H * y + rad * .7 * (1 + .25 * r.uniform(-1, 1)) * math.sin(k * math.pi / 4)) for k in range(8)]
        g.append(f'<path d="{smooth(pts_, closed=True)}" fill="{c}" fill-opacity="{.85 if dark else .6}"/>')
    g.append("</g>")
    body.append("".join(g))
    return doc("fluid", "\n".join(body), defs)



def contours(p, dark):
    r = random.Random(71)
    defs = sky(p) + blur("glow", 120)
    body = [f'<rect width="{W}" height="{H}" fill="url(#sky)"/>',
            f'<circle cx="{W * .68}" cy="{H * .46}" r="700" fill="{p["blue"]}" fill-opacity="{.35 if dark else .18}" filter="url(#glow)"/>']
    for cx, cy, count in ((W * .68, H * .46, 26), (W * .18, H * .9, 16)):
        harm = [(k, r.uniform(.04, .1) / k ** .6, r.uniform(0, 2 * math.pi)) for k in range(2, 6)]
        for j in range(1, count + 1):
            base = 70 * j
            pts_ = []
            for s in range(48):
                th = s / 48 * 2 * math.pi
                rr = base * (1 + sum(a * math.sin(k * th + ph + j * .07) for k, a, ph in harm))
                pts_.append((cx + rr * math.cos(th) * 1.25, cy + rr * math.sin(th)))
            o = max(.12, (.75 if dark else .6) - j * .022)
            body.append(f'<path d="{smooth(pts_, closed=True)}" fill="none" stroke="{p["cyan"] if dark else p["line"]}" stroke-opacity="{o:.2f}" stroke-width="{4 if j % 5 else 7}"/>')
    return doc("contours", "\n".join(body), defs)



def mix(a, b, t):
    """Blend two #RRGGBB colours: t=0 gives a, t=1 gives b."""
    t = min(1.0, max(0.0, t))
    ca = [int(a[i:i + 2], 16) for i in (1, 3, 5)]
    cb = [int(b[i:i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{round(x + (y - x) * t):02X}" for x, y in zip(ca, cb))


DIRECTIONS = {"aurora": aurora, "glass": glass, "fluid": fluid, "contours": contours}
for name, make in DIRECTIONS.items():
    if ONLY and name not in ONLY:
        continue
    (OUT / f"{name}-light.svg").write_text(make(LIGHT, False), encoding="utf-8")
    (OUT / f"{name}-dark.svg").write_text(make(DARK, True), encoding="utf-8")
print(len(DIRECTIONS) if not ONLY else len(ONLY), "pairs")
